'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const {prepareRepository,backupComponent,checkRepository,readComponent,commitBundle}=require('../repository.cjs');
const {execFileSync}=require('node:child_process');
const {runBinaryPipeline}=require('../safe-process.cjs');
async function main(){
  const repoId=crypto.randomBytes(16).toString('hex');
  const root=path.join(process.env.LOCALAPPDATA,'ClassifiedsRecovery/phase7/repositories');
  let repo;
  assert.doesNotThrow(()=>{repo=prepareRepository({root,repoId,create:true});},'fresh encrypted repository must initialize');
  assert.throws(()=>prepareRepository({root,repoId,create:true}));
  assert.throws(()=>prepareRepository({root,repoId:crypto.randomBytes(16).toString('hex'),create:false}));
  const producer={command:process.execPath,args:['-e','process.stdout.write(Buffer.from([0,255,13,10,128,0]));']};
  const run=crypto.randomBytes(8).toString('hex');
  const receipt=await backupComponent(repo,'database.dump',producer,{run,sourceKind:'synthetic'});
  checkRepository(repo);
  const verify={command:process.execPath,args:['-e','const b=[];process.stdin.on("data",c=>b.push(c));process.stdin.on("end",()=>process.exit(Buffer.concat(b).equals(Buffer.from([0,255,13,10,128,0]))?0:2));']};
  const result=await runBinaryPipeline(readComponent(repo,receipt.snapshotId,'database.dump'),verify,{maxBytes:100,timeoutMs:10000});
  assert.equal(result.sha256,receipt.sha256);assert.equal(result.bytes,receipt.bytes);
  const reopened=prepareRepository({root,repoId,create:false});
  checkRepository(reopened);
  await assert.rejects(backupComponent(repo,'keys.json',{command:process.execPath,args:['-e','process.stdout.write("partial");process.exitCode=3;']},{run,sourceKind:'synthetic'}));
  const helper=(mode,id)=>execFileSync('C:/Windows/System32/WindowsPowerShell/v1.0/powershell.exe',['-NoLogo','-NoProfile','-NonInteractive','-ExecutionPolicy','RemoteSigned','-File',path.resolve(__dirname,'../key-store.ps1'),'-Mode',mode,'-RepoId',id],{windowsHide:true,stdio:['ignore','pipe','pipe'],timeout:15000});
  const password=helper('Read',repoId).toString('base64');
  const tool=JSON.parse(fs.readFileSync(path.resolve(__dirname,'../tool-lock.json')));
  const copyId=crypto.randomBytes(16).toString('hex');helper('CreateRepository',copyId);
  const copyPath=path.join(root,copyId);fs.cpSync(repo.path,copyPath,{recursive:true,errorOnExist:true,force:false});
  assert.throws(()=>prepareRepository({root,repoId:copyId,create:false}));
  const invoke=(args,pass=password)=>execFileSync(tool.executable,['--no-cache','--repo',copyPath,...args],{env:{SystemRoot:process.env.SystemRoot,TEMP:process.env.TEMP,RESTIC_PASSWORD:pass},windowsHide:true,stdio:['ignore','pipe','pipe'],timeout:30000});
  assert.throws(()=>invoke(['check','--read-data'],crypto.randomBytes(32).toString('base64')));
  invoke(['check','--read-data']);
  const restored=invoke(['dump',receipt.snapshotId,'/database.dump']);
  assert.ok(restored.equals(Buffer.from([0,255,13,10,128,0])));
  function walk(dir){return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);}
  const pack=walk(path.join(copyPath,'data'))[0];assert.ok(pack);
  const content=fs.readFileSync(pack);content[content.length-1]^=1;fs.writeFileSync(pack,content);
  assert.throws(()=>invoke(['check','--read-data']));
  checkRepository(repo);
  const components=[receipt];
  for(const kind of ['media.tar','keys.json','catalog.json','source.tar','application-image.tar'])components.push(await backupComponent(repo,kind,producer,{run,sourceKind:'synthetic'}));
  const bundle={complete:true,run,sourceKind:'synthetic',keyId:repoId,components};
  await assert.rejects(commitBundle(repo,{...bundle,components:components.slice(1)}));
  await assert.rejects(commitBundle(repo,{...bundle,keyId:copyId}));
  await assert.rejects(commitBundle(repo,{...bundle,components:components.map(c=>({...c,sha256:'f'.repeat(64)}))}));
  const bundleId=await commitBundle(repo,bundle);
  const resultRecord={pass:true,repoId,repoPath:repo.path,snapshotId:receipt.snapshotId,bundleId,negativeCopyId:copyId,bytes:result.bytes,checks:15,checkExit:0,binaryRoundtrip:true,databaseRestoreVerified:false};
  fs.writeFileSync(path.resolve(__dirname,`../../../docs/phase7/task-2-restic-roundtrip-${repoId}.json`),JSON.stringify(resultRecord,null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify(resultRecord));
}
main().catch(e=>{console.log(JSON.stringify({pass:false,category:e.code==='ERR_ASSERTION'?'repository_assertion_failed':'restic_roundtrip_failed'}));process.exitCode=1;});
